r"""`segment_sales` — 부문별 매출을 `수출 + 내수 = 합계` 로 검산해 낸다.

## 무엇을 지키는 시험인가

`Q-104` 는 같은 공시 안에 표가 **둘** 있고 부문값이 1 씩 다르다. 답변은 세 판 모두 비중
표를, 골든은 매출실적 표를 쓴다. 둘 다 내적으로 맞고 합계는 11,314,459 로 같다 — 원문
자체의 반올림 차다. 가릴 잣대는 산술이고, 이 줄은 그 산술이 맞는 삼중항만 담는다.

그래서 가장 중요한 시험은 **검산이 안 맞으면 침묵하는가** 다. 그 문이 죽으면 이 줄은
「자신 있게 틀린 수」를 내는 기계가 된다.
"""
import pytest

from argus import ablation
from argus.agent import aggregate

#: `Q-104` 근거의 매출실적 표. 코퍼스에서 그대로 옮겼다 — 마크다운 열 수가 행마다 다른
#: 것까지 그대로다. 원문의 그 흐트러짐을 견디는지가 이 시험의 절반이다.
Q104 = """\
| 사업부문 | 매출유형 | 품 목 |  | 제53기 | 제52기 | 제51기 |
|---|---|---|---|---|---|---|
| 컴포넌트 | 제 품상 품용 역기타매출 | 수동소자(MLCC 등) | 수출 | 5,006,765 | 4,307,441 | 3,762,448 |
| 내수 | 191,737 | 154,609 | 140,574 |  |  |  |
| 합계 | 5,198,502 | 4,462,050 | 3,903,022 |  |  |  |
| 패키지솔루션 | 제 품상 품용 역기타매출 | 반도체패키지기판 | 수출 | 2,266,771 | 2,006,869 | 1,688,535 |
| 내수 | 34,982 | 27,788 | 28,843 |  |  |  |
| 합계 | 2,301,753 | 2,034,657 | 1,717,378 |  |  |  |
| 광학솔루션 | 제 품상 품용 역기타매출 | 카메라모듈 | 수출 | 3,615,414 | 3,534,086 | 2,993,994 |
| 내수 | 198,790 | 263,310 | 278,018 |  |  |  |
| 합계 | 3,814,204 | 3,797,396 | 3,272,012 |  |  |  |
| 합 계 |  |  | 수출 | 10,888,950 | 9,848,396 | 8,444,977 |
| 내수 | 425,509 | 445,707 | 447,435 |  |  |  |
| 합계 | 11,314,459 | 10,294,103 | 8,892,412 |  |  |  |
"""
ASK = "삼성전기 2025년 사업보고서(제53기)의 사업부문별 매출을 알려줘."


def line(evidence=Q104, question=ASK, arm="A72"):
    with ablation.use(arm):
        return aggregate.segment_sales(evidence, question)


def test_골든의_세_수를_낸다():
    """비중 표 쪽(5,198,501 · 3,814,205)이 아니라 검산이 맞는 쪽이다."""
    out = line()
    assert "컴포넌트 5,006,765 + 191,737 = **5,198,502**" in out
    assert "패키지솔루션 2,266,771 + 34,982 = **2,301,753**" in out
    assert "광학솔루션 3,615,414 + 198,790 = **3,814,204**" in out


def test_총계_행은_담지_않는다():
    """`Q-104` 의 합계 요점은 질문 범위 밖이라 이미 걷어냈다. 여기서 실으면 되돌리는 셈이다."""
    assert "11,314,459" not in line()
    assert "10,888,950" not in line()


def test_검산이_안_맞으면_그_부문을_버린다():
    """🔴 이 시험이 죽으면 이 줄은 자신 있게 틀린 수를 내는 기계가 된다."""
    broken = Q104.replace("| 합계 | 5,198,502 |", "| 합계 | 5,198,999 |")
    out = line(broken)
    assert "5,198,999" not in out and "5,198,502" not in out
    assert "컴포넌트" not in out
    assert "2,301,753" in out, "나머지 부문은 살아 있어야 한다"


def test_부문이_둘_미만이면_침묵한다():
    """하나는 「부문별」이 아니다."""
    only_one = "\n".join(Q104.splitlines()[:5])
    assert line(only_one) == ""


@pytest.mark.parametrize("question", [
    "LG에너지솔루션의 제6기 연결 매출액과 두산에너빌리티의 제63기 연결 매출액 중 어느 쪽이 큰지",
    "두산에너빌리티 요약재무정보에서 제63기 연결 자산총계와 별도 자산총계의 차이는 몇 백만원인가?",
    "삼성전기의 최대주주는 누구야",
])
def test_비교_차이_문항에는_안_든다(question):
    """`Q-049`·`Q-051` 실측 — 표 꼴은 잡히지만 부문 분해가 답이 아니라 잡음이다."""
    assert line(question=question) == ""


@pytest.mark.parametrize("arm", ["A65", "A70", "A71"])
def test_스위치가_꺼진_팔은_침묵한다(arm):
    assert line(arm=arm) == ""


def test_표가_없으면_침묵한다():
    assert line("근거 본문에 표가 하나도 없다. 부문별 매출은 컴포넌트가 가장 크다.") == ""


def test_내수_행이_아니면_삼중항이_아니다():
    """가운데 행의 첫 칸이 `내수` 여야 한다. 아무 세 줄이나 더해 보지 않는다."""
    other = Q104.replace("| 내수 | 191,737 |", "| 기타 | 191,737 |")
    assert "5,198,502" not in line(other)
