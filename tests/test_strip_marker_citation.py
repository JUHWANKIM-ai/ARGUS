r"""`strip_marker_citation` — 답변이 표지를 출처로 댄 자리를 걷어낸다.

## 무엇을 지키는 시험인가

표지(`[결정적 집계]` 따위)는 우리가 근거 앞에 붙인 **내부 이름표**다. 생성 프롬프트는
그것을 모르므로 모델은 대괄호를 그냥 출처로 읽고 그대로 인용한다. `A65` 서버 3회 실측으로
336건 중 **36건**(12문항 × 3회)이 그 모양이다 — 흔들림이 아니라 규칙이다.

아래 시험 중 둘은 **실제로 망가뜨렸던 것**을 못 박는다.

  ① `(주)두산` 처럼 회사 이름이 괄호를 품는 자리에서 정규식이 끊겼다
  ② 지운 자리를 답변 전체 공백 정리로 다듬어 마크다운 들여쓰기가 무너졌다
"""
import pytest

from argus import ablation
from argus.agent.pipeline import strip_marker_citation


def fix(answer, arm="A76"):
    with ablation.use(arm):
        return strip_marker_citation(answer)


def test_표지뿐인_괄호는_통째로_지운다():
    """`Q-018` 실측. 날짜만 남은 근거는 근거가 아니다."""
    out, fixes = fix("계약금액이 275,900,000,000원 증가했습니다. (근거: 결정적 집계, 2023-07-03)")
    assert out == "계약금액이 275,900,000,000원 증가했습니다."
    assert fixes == ["표지뿐인 근거 괄호 1곳을 지웠다"]


def test_값어치_있는_것이_남으면_표지만_뺀다():
    """`Q-034`·`Q-116` 실측. 남은 표기는 참이므로 지우면 관측을 잃는다."""
    out, _ = fix("(근거: 결정적 집계, 2025년 3~4월 각 공급계약 해지 보고서들)")
    assert out == "(근거: 2025년 3~4월 각 공급계약 해지 보고서들)"
    out, _ = fix("(근거: 결정적 조회 및 각 회사별 단일판매 공급계약 체결 공시)")
    assert out == "(근거: 각 회사별 단일판매 공급계약 체결 공시)"


def test_접수번호가_남으면_지키다():
    """`Q-115` 실측 — 진짜 표기가 섞여 있다."""
    out, _ = fix("(근거: 결정적 집계, 2025년 공시분, 접수번호 20251128800125, 20250117800487)")
    assert "20251128800125" in out and "20250117800487" in out
    assert "결정적" not in out


def test_회사_이름이_괄호를_품어도_끊기지_않는다():
    """🔴 `Q-106` 실측. `[^)]*` 로 잡으면 `(주)` 에서 끊겨 뒤가 문장에 나뒹군다."""
    out, _ = fix("(근거: 결정적 집계 (주)두산 보고 보유비율 추이, 2023-10-13~2026-02-27)")
    assert out == "(근거: (주)두산 보고 보유비율 추이, 2023-10-13~2026-02-27)"


def test_마크다운_들여쓰기를_지킨다():
    """🔴 `Q-034`·`Q-106` 실측. 지운 자리를 답변 전체 공백 정리로 다듬었더니
    `   - 계약 상대:` 가 ` - 계약 상대:` 가 됐다."""
    answer = ("1. 첫째 공시\n"
              "   - 계약 상대: ㈜태영건설\n"
              "   - 해지 금액: 72,200,000,000원\n"
              "(근거: 결정적 집계, 2025-03-31)")
    out, _ = fix(answer)
    assert "   - 계약 상대: ㈜태영건설" in out
    assert "   - 해지 금액: 72,200,000,000원" in out


def test_문장_속_언급은_위_근거로_바꾼다():
    """`Q-117` 실측. 결정적 줄은 정말로 근거 안에 있으므로 이것은 참인 말이다."""
    out, fixes = fix("이는 결정적 집계에 명시되어 있습니다.")
    assert out == "이는 위 근거에 명시되어 있습니다."
    assert fixes == ["문장 속 표지를 '위 근거' 로 바꿨다"]


def test_괄호가_여럿이면_다_고친다():
    out, fixes = fix("가. (근거: 결정적 집계) 나. (근거: 결정적 조회, 접수번호 20250325800001)")
    assert "결정적" not in out
    assert "20250325800001" in out
    assert len(fixes) == 2


def test_표지가_없으면_한_글자도_안_건드린다():
    answer = "계약금액은 1,102,000,000,000원입니다. (근거: 접수번호 20231214801332)"
    out, fixes = fix(answer)
    assert out == answer and fixes == []


def test_표지를_안_담은_괄호는_그대로_둔다():
    answer = "(근거: 결정적 집계) 그리고 (근거: 접수번호 20231214801332)"
    out, _ = fix(answer)
    assert "(근거: 접수번호 20231214801332)" in out


def test_닫히지_않은_괄호는_손대지_않는다():
    """끝을 모르면 무엇을 지울지도 모른다. 그때는 문장 속 치환만 남는다."""
    out, _ = fix("(근거: 결정적 집계, 접수번호 20231214801332")
    assert out == "(근거: 위 근거, 접수번호 20231214801332"


@pytest.mark.parametrize("arm", ["A65", "A74", "A75"])
def test_스위치가_꺼진_팔은_안_건드린다(arm):
    answer = "(근거: 결정적 집계, 2023-07-03)"
    assert fix(answer, arm) == (answer, [])


def test_빈_답변():
    assert fix("") == ("", [])
    assert fix(None) == (None, [])
