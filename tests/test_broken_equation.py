r"""`fix_broken_equation` — 피연산자가 결과를 못 만드는 등식에서 거짓 유도를 지운다.

## 무엇을 지키는 시험인가

`Q-113` 답변이 이렇게 적었다(`A65` 서버 r1).

    - 계산식: 1,328,800,000,000 + 499,950,000,000 = **1,828,750,000,000원**
    - 증가분 = 1,828,750,000,000 - 526,570,000,000 = **526,570,000,000원**

앞 줄은 맞다. 뒷 줄은 **결과를 피감수 자리에 다시 쓴 것**이라 산술이 성립하지 않는다
(실제 `1,302,180,000,000`). 결과 자체는 맞다 — 결정적 줄이 그 값을 주었다. 그래서 이
문항은 정확성에는 안 잡히고 추론 논리성에만 걸린다.

가장 중요한 시험은 **결과가 결정적 줄에 없으면 침묵한다**는 것이다. 그 문이 죽으면 결과가
틀린 등식에서 유도를 지워 **틀린 값만 남긴다**.
"""
import pytest

from argus import ablation
from argus.agent import aggregate

#: `Q-113` 근거의 차 줄. 코퍼스에서 그대로 옮겼다.
EVIDENCE = (
    "- [결정적 집계] 정정 전후 금액 변동 (평택 사업분 · 계약상대 삼성전자) — "
    "삼성중공업 499,950,000,000 − 392,590,000,000 = 107,360,000,000 · "
    "삼성E&A 1,328,800,000,000 − 909,590,000,000 = 419,210,000,000 · "
    "합계 **526,570,000,000원** (이 값은 시스템이 위 근거의 금액 필드에서 직접 계산한 "
    "것이다. 답변의 해당 수치는 이 값을 그대로 쓰고 다시 계산하지 않는다.)"
)
ANSWER = ("5. **증가분 계산**\n"
          "   - 계산식: 1,328,800,000,000 + 499,950,000,000 = **1,828,750,000,000원**\n"
          "   - 증가분 = 1,828,750,000,000 - 526,570,000,000 = **526,570,000,000원**")


def fix(answer=ANSWER, evidence=EVIDENCE, arm="A79"):
    with ablation.use(arm):
        return aggregate.fix_broken_equation(answer, evidence)


def test_거짓_유도를_지우고_결과를_남긴다():
    out, fixes = fix()
    assert "   - 증가분 = **526,570,000,000원**" in out
    assert "1,828,750,000,000 - 526,570,000,000" not in out
    assert len(fixes) == 1 and "실제 1,302,180,000,000" in fixes[0]


def test_성립하는_등식은_한_글자도_안_건드린다():
    """앞 줄(`1,328,800,000,000 + 499,950,000,000 = 1,828,750,000,000`)은 맞다."""
    out, _ = fix()
    assert "- 계산식: 1,328,800,000,000 + 499,950,000,000 = **1,828,750,000,000원**" in out


def test_결과가_결정적_줄에_없으면_침묵한다():
    """🔴 이 문이 죽으면 결과가 틀린 등식에서 유도를 지워 **틀린 값만 남긴다.**

    어느 쪽이 틀렸는지 모를 때 답은 침묵이다.
    """
    assert fix(evidence="- 근거에 결정적 줄이 없다") == (ANSWER, [])
    #: 결정적 줄은 있으나 그 값이 아니다.
    other = EVIDENCE.replace("526,570,000,000", "111,111,111,111")
    assert fix(evidence=other) == (ANSWER, [])


def test_덧셈도_본다():
    answer = "합계 = 1,000,000,000 + 2,000,000,000 = **526,570,000,000원**"
    out, fixes = fix(answer)
    assert out == "합계 = **526,570,000,000원**"
    assert "실제 3,000,000,000" in fixes[0]


def test_유도가_둘이면_둘_다_본다():
    answer = ("가. 9,000,000,000 - 1,000,000,000 = **526,570,000,000원**\n"
              "나. 8,000,000,000 - 2,000,000,000 = **526,570,000,000원**")
    out, fixes = fix(answer)
    assert out == "가. **526,570,000,000원**\n나. **526,570,000,000원**"
    assert len(fixes) == 2


def test_꼬리는_건드리지_않는다():
    """시스템이 붙인 註는 검증기가 관측한 것을 적은 것이다 — `split_tail` 의 규율이다."""
    answer = (ANSWER
              + "\n\n(주의: 자동 검증에서 결함이 발견되었습니다 — "
                "1,828,750,000,000 - 526,570,000,000 = 526,570,000,000)")
    out, _ = fix(answer)
    assert "(주의: 자동 검증에서 결함이 발견되었습니다 — " \
           "1,828,750,000,000 - 526,570,000,000 = 526,570,000,000)" in out


def test_등식이_없으면_침묵한다():
    assert fix("증가분은 약 5,265억원입니다.") == ("증가분은 약 5,265억원입니다.", [])


@pytest.mark.parametrize("arm", ["A65", "A77", "A78"])
def test_스위치가_꺼진_팔은_침묵한다(arm):
    assert fix(arm=arm) == (ANSWER, [])


def test_빈_입력():
    assert fix("") == ("", [])
    assert fix(None) == (None, [])
    assert fix(evidence="") == (ANSWER, [])
