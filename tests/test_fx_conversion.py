r"""`fx_conversion` — 공시가 스스로 밝힌 원화 환산을 문면에서 그대로 옮긴다.

## 무엇을 지키는 시험인가

`Q-101` 골든 요점2(*"2025년 3월 24일 매매기준율(1,466.9원/달러)로 환산한 8조 5,080억원이
함께 적혀 있다"*)가 요구하는 두 수는 근거 안에 **그대로 있다.** `- 기타 투자판단과 관련한
중요사항:` 필드의 산문 속이다. 답변은 세 판 모두 `$58억` 만 적었다.

가장 중요한 시험은 **세 조각이 다 있을 때만 낸다**는 것이다. 환산액만 적으면 무엇을
무엇으로 환산했는지 모르고, 환율만 적으면 답이 아니다.
"""
import pytest

from argus import ablation
from argus.agent import aggregate

#: `Q-101` 근거의 그 문장. 코퍼스에서 그대로 옮겼다.
BODY = ("- 기타 투자판단과 관련한 중요사항: 1) 본 건은 당사와 현대차그룹 등이 공동 "
        "투자하여 미국 남동부 루이지애나 주에 58억 달러 규모의 자동차강판 특화 전기로 "
        "제철소를 건설하는 건 입니다. 상기 2. '투자금액' $58억을 원화 환산 시 "
        "8조 5,080억원이며, 이는 2025년 3월 24일 서울외국환중개 매매기준율"
        "(1,466.9원/달러)을 적용한 금액입니다.")
ASK = "현대제철이 2025년 3월에 공시한 미국 전기로 제철소 건설 추진 건의 투자금액을 근거와 함께 알려줘."


def line(evidence=BODY, question=ASK, arm="A74"):
    with ablation.use(arm):
        return aggregate.fx_conversion(evidence, question)


def test_골든의_두_수를_낸다():
    """`8조 5,080억원` 과 `1,466.9원/달러`. 요점2 가 요구하는 것이 그 둘이다."""
    out = line()
    assert "$58억 = **8조 5,080억원**" in out
    assert "2025년 3월 24일 서울외국환중개 매매기준율 1,466.9원/달러" in out


def test_계산했다고_말하지_않는다():
    """🔴 `58억 × 1,466.9` 를 우리가 계산하지 않는다.

    공시가 적은 환산액과 우리 계산이 어긋나면(반올림·기준일 차이로 흔히 어긋난다) 우리
    값이 **공시와 다른 수**가 되고, 심사자가 원공시와 맞춰 볼 때 곧바로 드러난다.
    그래서 `[결정적 집계]` 가 아니라 `[결정적 조회]` 이고 문면에서 옮겼다고 적는다.
    """
    out = line()
    assert out.startswith("- [결정적 조회]")
    assert "그대로 옮긴 것이다" in out
    assert "계산한 것이 아니므로" in out


@pytest.mark.parametrize("drop, missing", [
    ("$58억을 ", "외화 금액"),
    ("8조 5,080억원", "환산액"),
    ("(1,466.9원/달러)", "환율"),
    ("2025년 3월 24일 ", "기준일"),
])
def test_한_조각이라도_없으면_침묵한다(drop, missing):
    """세 조각(외화 금액 · 환산액 · 환율)과 기준일이 다 있어야 뜻이 선다."""
    assert line(BODY.replace(drop, "")) == "", missing


def test_그런_문장이_둘이면_침묵한다():
    """어느 것이 답인지 모른다."""
    assert line(BODY + "\n" + BODY.replace("58억", "70억")) == ""


@pytest.mark.parametrize("question", [
    "현대제철의 최대주주는 누구야",
    "그 공시의 접수번호를 알려줘",
])
def test_금액을_묻지_않으면_안_든다(question):
    """꼴 자체가 352건에 한 자리뿐이라 여벌 문이지만, 같은 공시가 다른 질문에 걸릴 때
    질문이 안 물은 수가 답에 끼는 것을 막는다."""
    assert line(question=question) == ""


@pytest.mark.parametrize("arm", ["A65", "A72", "A73"])
def test_스위치가_꺼진_팔은_침묵한다(arm):
    assert line(arm=arm) == ""


def test_환율_낱말만_있으면_안_든다():
    """`Q-067` 실측 — `환율` 은 나오지만 환산 문장은 아니다."""
    assert line("- 주요내용: 환율 변동에 따른 위험을 관리하고 있습니다.") == ""


def test_근거가_비면_침묵한다():
    assert line("") == ""
    assert line(None) == ""
